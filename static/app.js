function featureFmt(name) {
  const d = (META().describe || {})[name];
  if (!d || d.min === undefined) return autoNum;
  const isInt = Number.isInteger(d.min) && Number.isInteger(d.max);
  if (isInt) return v => num(v, 0);
  const span = d.max - d.min;
  const dec = span > 100 ? 0 : span > 10 ? 1 : span > 1 ? 2 : 4;
  return v => num(v, dec);
}

