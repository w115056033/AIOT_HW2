function loadScript(src) {
  return new Promise((resolve, reject) => {
    const s = document.createElement('script');
    s.src = src;
    s.onload = resolve;
    s.onerror = () => reject(new Error('cannot load ' + src));
    document.head.appendChild(s);
  });
}

async function ensureData(cfg) {
  if (window.PROBLEM_DATA && window.PROBLEM_DATA[cfg.id]) return window.PROBLEM_DATA[cfg.id];
  if (cfg.dataFile) {
    try { await loadScript(cfg.dataFile); } catch (e) { /* fall through to fetch */ }
    if (window.PROBLEM_DATA && window.PROBLEM_DATA[cfg.id]) return window.PROBLEM_DATA[cfg.id];
  }
  if (!cfg.dataFile) return null;            // dynamically analysed problems live in memory only
  for (const url of [`/api/models?problem=${cfg.id}`, JSON_FILES[cfg.id]]) {
    try {
      const r = await fetch(url);
      if (!r.ok) continue;
      const j = await r.json();
      if (j.models) return j;
    } catch (e) { /* keep trying */ }
  }
  return null;
}

async function init() {
  const list = window.PROBLEMS || [];
  if (!list.length) {
    document.body.insertAdjacentHTML('afterbegin',
      '<div class="warn-banner" style="display:block;margin:20px">⚠️ 找不到 problem 設定（static/problems.js）。</div>');
    return;
  }
  const sel = document.getElementById('problemSelect');
  sel.innerHTML = list.map(p => `<option value="${p.id}">${p.label}</option>`).join('');

  const fromHash = (location.hash.match(/p=([\w-]+)/) || [])[1];
  const stored = (() => { try { return localStorage.getItem('mlr-problem'); } catch (e) { return null; } })();
  const start = list.find(p => p.id === fromHash) || list.find(p => p.id === stored) || list[0];

  setTheme(state.theme);
  await switchProblem(start.id, { silent: true });
}

let switchToken = 0;

async function switchProblem(id, opts = {}) {
  const list = window.PROBLEMS || [];
  const cfg = list.find(p => p.id === id) || list[0];
  if (!cfg) return;
  if (CFG && CFG.id === cfg.id && DATA && !opts.force) return;
  const myToken = ++switchToken;

  const mask = document.createElement('div');
  mask.className = 'loading-mask';
  mask.textContent = `載入 ${cfg.short || cfg.id} 的模型資料…`;
  document.body.appendChild(mask);

  const payload = await ensureData(cfg);
  mask.remove();
  if (myToken !== switchToken) return;          // a newer switch superseded this one

  if (!payload || !payload.models) {
    document.body.insertAdjacentHTML('afterbegin',
      `<div class="warn-banner" style="display:block;margin:20px">⚠️ 找不到 <b>${esc(cfg.id)}</b> 的模型資料
       （${esc(cfg.dataFile)} / ${esc(JSON_FILES[cfg.id] || '')}）。請先執行對應的 build_*_data.py。</div>`);
    return;
  }

  CFG = cfg;
  DATA = payload;
  state.problem = cfg.id;
  state.compareAll = false;
  state.apiConnected = null;                 // re-probed for every problem
  state.algo = DATA.models[payload.meta.final_decision && payload.meta.final_decision.algo]
    ? payload.meta.final_decision.algo : ALGOS()[0];
  state.k = Math.max(1, Math.min(payload.meta.final_decision ? (payload.meta.final_decision.k || 2) : 2, KMAX()));

  try { localStorage.setItem('mlr-problem', cfg.id); } catch (e) { /* ignore */ }
  history.replaceState(null, '', '#' + (cfg.id === list[0].id ? 'overview' : 'p=' + cfg.id));

  document.getElementById('problemSelect').value = cfg.id;
  setHTML('problemHint', tok(cfg.hint || ''));
  document.title = cfg.pageTitle || cfg.label;
  const desc = document.getElementById('page-desc');
  if (desc && cfg.metaDescription) desc.setAttribute('content', cfg.metaDescription);
  setText('nav-title', cfg.navTitle || cfg.label);
  setText('nav-sub', cfg.navSub || '');

  // wipe stale charts so scales/labels are rebuilt for the new k-range
  Object.values(charts).forEach(c => { try { c.destroy(); } catch (e) { /* ignore */ } });
  charts = {};

  renderStaticText();
  syncNavOffset();
  renderHero();
  renderStepper();
  buildControls();
  renderCrispdmData();
  renderAll();
  detectApi();
  syncNavOffset();

  if (typeof Chart === 'undefined') {
    const w = document.getElementById('chart-warning');
    if (w) w.style.display = 'block';
  }
}

document.addEventListener('change', e => {
  if (e.target && e.target.id === 'problemSelect') switchProblem(e.target.value);
});

