/* ---------------------------------------------------------- prediction -- */
function coefValue(c, inp) {
  const f = c.feature;
  if (f.startsWith('Intercept')) return 1;
  const specs = META().predictor_inputs;
  const r = specs.find(i => i.type === 'range' && i.feature === f);
  if (r) return inp[r.key];
  const s = specs.find(i => i.type === 'select' && i.prefix && f.startsWith(i.prefix));
  if (s) return inp[s.key] === f.slice(s.prefix.length) ? 1 : 0;
  return 0;
}

function featureMean(name) {
  const m = META();
  const d = (m.describe || {})[name];
  if (d && d.mean !== undefined && d.mean !== null) return d.mean;
  for (const s of m.predictor_inputs) {
    if (s.type === 'select' && s.prefix && name.startsWith(s.prefix)) {
      const val = name.slice(s.prefix.length);
      return m.rows.filter(r => r[s.feature] === val).length / m.rows.length;
    }
  }
  return 0;
}

function predictLocal(e, inp) {
  const parts = [];
  let total = 0, baseline = 0;
  e.coefficients.forEach(c => {
    const v = coefValue(c, inp);
    const contribution = c.coef * v;
    total += contribution;
    if (c.feature.startsWith('Intercept')) {
      baseline += contribution;
    } else {
      const mu = featureMean(c.feature);
      baseline += c.coef * mu;
      parts.push({ feature: c.feature, value: v, coef: c.coef, contribution, delta: c.coef * (v - mu) });
    }
  });
  return { total, parts, baseline };
}

