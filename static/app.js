function columnFormatters() {
  const m = META();
  const fmt = {};
  (m.dataset.columns || []).forEach(c => {
    if (c.kind === 'target') { fmt[c.key] = v => money(v); return; }
    if (c.kind === 'categorical') { fmt[c.key] = v => esc(v); return; }
    const vals = m.rows.map(r => r[c.key]).filter(v => typeof v === 'number');
    const isInt = vals.every(v => Number.isInteger(v));
    const span = vals.length ? Math.max(...vals) - Math.min(...vals) : 0;
    const d = isInt ? 0 : span > 100 ? 0 : span > 10 ? 1 : span > 1 ? 2 : 4;
    fmt[c.key] = v => num(v, d);
  });
  return fmt;
}

function renderDatasetTable() {
  const m = META(), d = m.dataset, t = d.target;
  const cat = (d.categorical_features || [])[0];
  const sf = document.getElementById('stateFilter');
  const filterVal = (cat && sf && sf.parentElement.style.display !== 'none') ? sf.value : '';
  const sort = document.getElementById('sortSelect').value;
  const q = document.getElementById('searchBox').value.trim().toLowerCase();

  let rows = m.rows.slice();
  if (filterVal) rows = rows.filter(r => r[cat] === filterVal);
  if (q) rows = rows.filter(r => Object.values(r).some(v => String(v).toLowerCase().includes(q)));
  if (sort === 'target-desc') rows.sort((a, b) => b[t] - a[t]);
  else if (sort === 'target-asc') rows.sort((a, b) => a[t] - b[t]);
  else if (sort.endsWith('-desc')) {
    const f = sort.slice(0, -5);
    rows.sort((a, b) => (b[f] || 0) - (a[f] || 0));
  }

  const mean = rows.length ? avg(rows.map(r => r[t])) : 0;
  const cols = d.columns || [];
  const fmt = columnFormatters();
  const targetLast = cols.length && cols[cols.length - 1].kind === 'target';
  const body = rows.map(r => `<tr>
      ${cols.map(c => {
        const cls = c.kind === 'target' ? ' class="mono v-cyan"' : (c.kind === 'numeric' ? ' class="mono"' : '');
        return `<td${cls}>${(fmt[c.key] || autoNum)(r[c.key])}</td>`;
      }).join('')}</tr>`).join('') +
    (targetLast
      ? `<tr><td colspan="${Math.max(1, cols.length - 1)}" style="text-align:right;color:var(--muted)">顯示 ${rows.length} / ${m.rows.length} 筆 · 平均 ${esc(t)}</td>
      <td class="mono v-emerald">${money(mean)}</td></tr>`
      : `<tr><td colspan="${Math.max(1, cols.length)}" style="text-align:right;color:var(--muted)">顯示 ${rows.length} / ${m.rows.length} 筆 · 平均 ${esc(t)} <span class="mono v-emerald">${money(mean)}</span></td></tr>`);
  setHTML('dataset-table', `<thead><tr>${cols.map(c => `<th>${esc(c.label)}</th>`).join('')}</tr></thead><tbody>` + body + '</tbody>');
}
