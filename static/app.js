/** Currency / unit prefix of the active problem ('' for arbitrary datasets). */
const U = () => {
  try {
    const u = DATA.meta.dataset.unit;
    return (u === undefined || u === null) ? '$' : u;
  } catch (e) { return '$'; }
};
const money = (v, d = 0) => {
  if (v === null || v === undefined || isNaN(v)) return '—';
  const unit = U();
  let dec = d;
  if (!unit) {                       // unit-less datasets: keep small numbers readable
    const a = Math.abs(v);
    dec = a >= 1000 ? 0 : a >= 100 ? 1 : a >= 10 ? 2 : 3;
  }
  return (v < 0 ? '-' : '') + unit +
    Math.abs(v).toLocaleString('en-US', { minimumFractionDigits: dec, maximumFractionDigits: dec });
};
const axisNum = v => U()
  ? U() + Math.round(v).toLocaleString('en-US')
  : (Math.abs(v) >= 100 ? Math.round(v).toLocaleString('en-US')
    : Number(v).toLocaleString('en-US', { maximumFractionDigits: Math.abs(v) >= 10 ? 1 : 2 }));
const num = (v, d = 2) => (v === null || v === undefined || isNaN(v)) ? '—' :
  v.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
const pct = (v, d = 1) => (v === null || v === undefined || isNaN(v)) ? '—' : (v * 100).toFixed(d) + '%';
const pfmt = p => (p === null || p === undefined || isNaN(p)) ? '—' : (p < 0.0001 ? '< 0.0001' : p.toFixed(4));
const stars = p => (p === null || p === undefined) ? '' :
  (p < 0.001 ? ' ***' : p < 0.01 ? ' **' : p < 0.05 ? ' *' : '');
const sigClass = p => (p !== null && p !== undefined && p < 0.05) ? 'sig' : 'ns';
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const cssVar = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
const avg = a => a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0;
const autoNum = v => num(v, Math.abs(v) >= 1000 ? 0 : (Math.abs(v) >= 10 ? 1 : 3));
const featList = (fs, max = 4) => {
  if (!fs) return '—';
  if (fs.length <= max) return fs.map(esc).join(' + ');
  return fs.slice(0, max).map(esc).join(' + ') + ` … (+${fs.length - max})`;
};
const setHTML = (id, html) => { const el = document.getElementById(id); if (el) el.innerHTML = html; };
const setText = (id, txt) => { const el = document.getElementById(id); if (el) el.textContent = txt; };

