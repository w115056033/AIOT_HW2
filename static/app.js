/* --------------------------------------------------------- Flask API -- */
async function detectApi() {
  const badge = document.getElementById('api-badge');
  if (CFG && CFG.dynamic) {
    state.apiConnected = false;
    badge.className = 'badge';
    badge.textContent = '○ 自訂資料集（瀏覽器端計算）';
    setHTML('api-row',
      '<span class="badge">自訂資料集於瀏覽器端完成分析與預測，不經過後端 API</span>' +
      '<span class="mono" style="color:var(--dim)">重新整理頁面後需再次載入</span>');
    return;
  }
  try {
    const r = await fetch(`/api/summary?problem=${CFG.id}`, { headers: { Accept: 'application/json' } });
    if (!r.ok) throw new Error('no api');
    const j = await r.json();
    state.apiConnected = Array.isArray(j) && j.length > 0;
  } catch (err) {
    state.apiConnected = false;
  }
  badge.className = 'badge ' + (state.apiConnected ? 'ok' : '');
  badge.textContent = state.apiConnected ? '● Flask API 已連線' : '○ 靜態模式（GitHub Pages）';
  setHTML('api-row', state.apiConnected
    ? '<span class="badge ok">POST /api/predict 可用</span><span>前端即時計算與後端 API 結果同步比對中…</span>'
    : '<span class="badge">靜態模式：預測於瀏覽器以 JSON 係數即時計算，無需後端</span>');
  if (state.apiConnected && DATA) renderPrediction();   // run one comparison right away
}

let apiSyncTimer = null;
function syncApi(e, inp, localTotal) {
  if (!state.apiConnected) return;
  clearTimeout(apiSyncTimer);
  apiSyncTimer = setTimeout(async () => {
    try {
      const r = await fetch('/api/predict', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ problem: CFG.id, algo: e.algo, k: e.k, values: inp })
      });
      const j = await r.json();
      if (typeof j.prediction !== 'number') return;
      const diff = Math.abs(j.prediction - localTotal);
      setHTML('api-row',
        `<span class="badge ok">POST /api/predict</span>
         <span>後端 ${money(j.prediction)} ／ 前端 ${money(localTotal)}</span>
         <span class="badge ${diff < 1 ? 'ok' : 'warn'}">${diff < 1 ? '✓ 完全一致' : '差異 ' + money(diff)}</span>
         <span class="mono" style="color:var(--dim)">${esc(j.algorithm)} · k=${j.k}</span>`);
    } catch (err) { /* ignore */ }
  }, 220);
}

