/** Full-dataset statistics of the target (meta.describe), not just the displayed sample. */
function targetStats() {
  const m = META(), t = m.dataset.target;
  const d = (m.describe || {})[t] || {};
  const vals = m.rows.map(r => r[t]);
  const has = v => v !== undefined && v !== null && !isNaN(v);
  return {
    mean: has(d.mean) ? d.mean : avg(vals),
    min: has(d.min) ? d.min : Math.min(...vals),
    max: has(d.max) ? d.max : Math.max(...vals),
    median: has(d['50%']) ? d['50%'] : vals.slice().sort((a, b) => a - b)[Math.floor(vals.length / 2)]
  };
}

/* -------------------------------------------------------- {{token}} -- */
function tokenDict() {
  const m = META(), d = m.dataset, t = d.target;
  const ts = targetStats();
  const all = allEntries();
  const cv = m.cv_best, ho = m.holdout_best, fd = m.final_decision || {};
  const k = KMAX();
  const minCv = kk => Math.min(...ALGOS().map(a => entry(a, kk).cv_rmse));
  const baseline = m.baseline;
  const coefOf = name => {
    const c = (baseline.coefficients || []).find(x => x.feature === name);
    return c ? num(c.coef, 2) : '—';
  };
  return {
    n: num(d.rows, 0), raw_rows: num(d.raw_rows || d.rows, 0), raw_columns: num(d.raw_columns || d.columns.length, 0),
    train: num(d.train_rows, 0), test: num(d.test_rows, 0),
    features: num(d.features.length, 0), methods: num(ALGOS().length, 0), kmax: num(k, 0),
    target: t, target_label: d.target_label || t, unit: d.unit === undefined ? '$' : d.unit,
    dataset: esc(d.name), source: d.source || '',
    missing: num(d.missing_values, 0), imputed: num(d.missing_values, 0), dupes: num(d.duplicates, 0),
    random_state: d.random_state, cv_folds: d.cv_folds,
    sampled_rows: num(d.sampled_rows || d.rows, 0),
    dropped_count: num((d.dropped || []).length, 0),
    mean: money(ts.mean), min: money(ts.min), max: money(ts.max),
    median: money(ts.median),
    top: m.top_feature.name, top_corr: m.top_feature.corr.toFixed(3),
    cv_algo: cv.algo, cv_k: cv.k, cv_rmse: money(cv.cv_rmse), cv_std: money(cv.cv_rmse_std),
    ho_algo: ho.algo, ho_k: ho.k, ho_rmse: money(ho.rmse), ho_r2: ho.r2.toFixed(4), ho_mae: money(ho.mae),
    ho_cv_rmse: money(ho.cv_rmse),
    noise: money(m.noise_band),
    base_r2: baseline.r2.toFixed(4), base_r2_pct: pct(baseline.r2), base_rmse: money(baseline.rmse),
    base_cv: money(baseline.cv_rmse), base_k: num(baseline.features.length, 0),
    final_model: fd.model || ho.algo, final_features: (fd.features || ho.features).join(' + '),
    final_k: fd.k || ho.k, final_algo: fd.algo || ho.algo,
    final_rmse: money(fd.rmse || ho.rmse),
    sel_count: num((m.backward_elimination.retained || []).length, 0),
    back_dropped: num((m.backward_elimination.dropped || []).length, 0),
    k1_cv: money(minCv(1)), k8_cv: k >= 8 ? money(minCv(8)) : '—',
    models_entries: num(ALGOS().length * k, 0),
    mape: pct(ho.mae / ts.mean),
    coef_sqft: coefOf('sqft_living'),
    cv_best_desc: `<span class="mono">${cv.algo} · k=${cv.k}</span> → ${featList(cv.features, 5)}（CV RMSE ${money(cv.cv_rmse)}）`,
    ho_best_desc: `<span class="mono">${ho.algo} · k=${ho.k}</span> → ${featList(ho.features, 5)}（RMSE ${money(ho.rmse)}、R² ${ho.r2.toFixed(4)}）`,
    selected_tag: `${activeAlgo()} · k=${state.k}`,
    target_mean_label: `平均 ${t}`
  };
}
function tok(html) {
  if (html === null || html === undefined) return '';
  const dict = tokenDict();
  return String(html).replace(/\{\{(\w+)\}\}/g, (all, key) => {
    if (key === 'selected_tag') {
      return `<span id="predict-model-tag" class="mono v-cyan">${dict.selected_tag}</span>`;
    }
    return key in dict ? dict[key] : all;
  });
}

